// Blog data layer.
//
// Fetches posts from WordPress via our Express proxy at /api/blog/*. The proxy
// hides the WP URL from the client, forwards X-WP-Total / X-WP-TotalPages for
// pagination, and adds short-lived edge caching.
//
// WP REST shape is normalized into the BlogPost type via mapWpPost() so the
// component code consumes a clean, internal type rather than WP's quirky
// `{ rendered: "..." }` envelope shape.

export type BlogCategory = {
  name: string;
  slug: string;
};

export type BlogTag = BlogCategory;

export type BlogAuthor = {
  name: string;
  avatar?: string;
};

export type BlogImage = {
  // url = the full-size original. Keep for backward compat + for Article
  // schema (which wants highest-res available). For actual <img> rendering
  // in cards + related posts + hero, pick from the responsive sizes below.
  url: string;
  alt: string;
  width?: number;
  height?: number;
  // Responsive variants pre-generated by WordPress. Each one is a smaller
  // file than the full-size original. Picking the right size per use case
  // saves 10x–100x bandwidth vs. loading the full-res PNG everywhere.
  // Falls back to the full `url` when a size isn't available.
  sizes?: {
    thumbnail?: string;      // ~150x150
    medium?: string;         // ~300x170 — blog card thumbnails
    mediumLarge?: string;    // ~768x436 — related posts
    large?: string;          // ~1024x582 — article hero image
  };
};

// Pick the smallest image URL that'll look sharp at the given rendered
// width. Returns the full-size `url` as fallback when a sized variant
// isn't available (e.g. legacy posts, Arabic posts, etc.).
export function pickBlogImage(
  image: BlogImage | undefined,
  size: "thumbnail" | "card" | "related" | "hero",
): string | undefined {
  if (!image) return undefined;
  const s = image.sizes;
  if (!s) return image.url;
  switch (size) {
    case "thumbnail":
      return s.thumbnail ?? s.medium ?? image.url;
    case "card":
      return s.medium ?? s.mediumLarge ?? image.url;
    case "related":
      return s.mediumLarge ?? s.medium ?? image.url;
    case "hero":
      return s.large ?? s.mediumLarge ?? image.url;
  }
}

export type BlogLang = "en" | "ar";

export type BlogPost = {
  id: number;
  slug: string;
  title: string;
  excerpt: string; // rendered HTML — strip for plain-text uses
  content: string; // rendered HTML for the detail page body
  date: string;    // ISO timestamp
  readingTimeMinutes: number;
  author: BlogAuthor;
  featuredImage?: BlogImage;
  categories: BlogCategory[];
  tags: BlogTag[];
  lang: BlogLang;
  // Slug of this post's translation in the opposite language, when one
  // exists. Populated via Polylang's `translations` field on the WP REST
  // response. Used to emit reciprocal hreflang alternates so Google can
  // pair /blog/foo (EN) ↔ /ar/blog/bar (AR) at runtime + prerender.
  translationSlug: string | null;
  seo: {
    title?: string;
    description?: string;
  };
};

export type FetchPostsOptions = {
  page?: number;
  perPage?: number;
  category?: string;
  lang?: BlogLang;
};

export type PostsResponse = {
  posts: BlogPost[];
  totalPosts: number;
  totalPages: number;
  page: number;
};

const POSTS_PER_PAGE = 9;
const READING_WPM = 200;

// Minimal subset of the WP REST `/posts?_embed=true` response shape — only the
// fields we actually consume.
type WpEmbeddedTerm = { id: number; name: string; slug: string; taxonomy: string };
type WpEmbeddedAuthor = { name: string; avatar_urls?: Record<string, string> };
type WpEmbeddedMedia = {
  source_url: string;
  alt_text?: string;
  media_details?: {
    width?: number;
    height?: number;
    // WordPress auto-generates these responsive sizes on upload. Each one
    // is a smaller file we can serve instead of the full-res original.
    sizes?: Record<string, { source_url?: string; width?: number; height?: number }>;
  };
};

type WpPost = {
  id: number;
  date: string;
  slug: string;
  title: { rendered: string };
  content: { rendered: string };
  excerpt: { rendered: string };
  lang?: string; // added by our Polylang REST snippet
  // Polylang exposes translation pairs as { en: id, ar: id } pointing at
  // the counterpart post ID in the opposite language. Only present when
  // a translation has been created + published; missing = no pair.
  translations?: Record<string, number>;
  meta?: Record<string, unknown>;
  // Yoast SEO injects this when the plugin is active.
  yoast_head_json?: {
    title?: string;
    description?: string;
    og_title?: string;
    og_description?: string;
  };
  _embedded?: {
    author?: WpEmbeddedAuthor[];
    "wp:featuredmedia"?: WpEmbeddedMedia[];
    "wp:term"?: WpEmbeddedTerm[][];
  };
};

// Decodes WP-rendered HTML entities like "It&#8217;s" → "It's". Used for plain-
// text uses (page title, meta description) — content/excerpt that goes through
// dangerouslySetInnerHTML doesn't need this since the browser decodes it.
function decodeHtmlEntities(s: string): string {
  if (typeof document === "undefined") return s;
  const el = document.createElement("textarea");
  el.innerHTML = s;
  return el.value;
}

function mapWpPost(wp: WpPost): BlogPost {
  const featuredMedia = wp._embedded?.["wp:featuredmedia"]?.[0];
  const author = wp._embedded?.author?.[0];
  const allTerms = (wp._embedded?.["wp:term"] ?? []).flat();
  const categories = allTerms.filter((t) => t.taxonomy === "category");
  const tags = allTerms.filter((t) => t.taxonomy === "post_tag");

  const plainContent = wp.content.rendered.replace(/<[^>]*>/g, " ");
  const wordCount = plainContent.split(/\s+/).filter(Boolean).length;

  // Rank Math exposes its meta under `meta.rank_math_*` when REST is enabled
  // in plugin settings; Yoast uses `yoast_head_json`. We fall back through
  // both before defaulting to the excerpt.
  const meta = wp.meta ?? {};
  const seoTitle =
    (meta.rank_math_title as string | undefined) ||
    wp.yoast_head_json?.title ||
    undefined;
  const seoDescription =
    (meta.rank_math_description as string | undefined) ||
    wp.yoast_head_json?.description ||
    undefined;

  return {
    id: wp.id,
    slug: wp.slug,
    title: decodeHtmlEntities(wp.title.rendered),
    excerpt: wp.excerpt.rendered,
    content: wp.content.rendered,
    date: wp.date,
    readingTimeMinutes: Math.max(1, Math.round(wordCount / READING_WPM)),
    author: {
      name: author?.name ?? "PLACES Team",
      avatar: author?.avatar_urls?.["96"],
    },
    featuredImage: featuredMedia
      ? {
          url: featuredMedia.source_url,
          alt: featuredMedia.alt_text || decodeHtmlEntities(wp.title.rendered),
          width: featuredMedia.media_details?.width,
          height: featuredMedia.media_details?.height,
          // Pre-generated by WordPress on upload. Picking a smaller size
          // for cards/thumbnails saves 10x–100x bandwidth vs. loading the
          // full-res PNG (which can be 2+ MB per image).
          sizes: (() => {
            const wpSizes = featuredMedia.media_details?.sizes;
            if (!wpSizes) return undefined;
            return {
              thumbnail: wpSizes.thumbnail?.source_url,
              medium: wpSizes.medium?.source_url,
              mediumLarge: wpSizes.medium_large?.source_url,
              large: wpSizes.large?.source_url,
            };
          })(),
        }
      : undefined,
    categories: categories.map((c) => ({ name: c.name, slug: c.slug })),
    tags: tags.map((t) => ({ name: t.name, slug: t.slug })),
    lang: wp.lang === "ar" ? "ar" : "en",
    // Placeholder — the async fetch layer fills this in from Polylang's
    // translations pointer via a second WP call (see fetchPost below).
    translationSlug: null,
    seo: {
      title: seoTitle ? decodeHtmlEntities(seoTitle) : undefined,
      description: seoDescription ? decodeHtmlEntities(seoDescription) : undefined,
    },
  };
}

// Given a WP post's Polylang translations map + the caller's own language,
// fetch the counterpart post's slug via one lookup. Returns null when no
// translation exists (Polylang didn't expose one, or the counterpart isn't
// published yet). Fails silently on network error — better to skip the
// hreflang pair than to fabricate a URL that 404s.
async function resolveTranslationSlug(
  wp: WpPost,
  ownLang: BlogLang,
): Promise<string | null> {
  const otherLang = ownLang === "ar" ? "en" : "ar";
  const otherId = wp.translations?.[otherLang];
  if (!otherId) return null;
  try {
    const res = await fetch(`/api/blog/posts/by-id/${otherId}?_fields=slug`);
    if (!res.ok) return null;
    const data = (await res.json()) as { slug?: string };
    return typeof data.slug === "string" ? data.slug : null;
  } catch {
    return null;
  }
}

export async function fetchPosts(opts: FetchPostsOptions = {}): Promise<PostsResponse> {
  const page = opts.page ?? 1;
  const perPage = opts.perPage ?? POSTS_PER_PAGE;

  const params = new URLSearchParams();
  params.set("page", String(page));
  params.set("per_page", String(perPage));
  if (opts.category) params.set("category", opts.category);
  if (opts.lang) params.set("lang", opts.lang);

  const res = await fetch(`/api/blog/posts?${params.toString()}`);
  if (!res.ok) {
    // 400 means the page is past the last page — WP returns this for empty
    // pages. Treat as "no results" so the UI can render gracefully.
    if (res.status === 400) {
      return { posts: [], totalPosts: 0, totalPages: 1, page };
    }
    throw new Error(`Failed to fetch posts: ${res.status}`);
  }

  const data = (await res.json()) as WpPost[];
  const totalPosts = Number(res.headers.get("X-WP-Total") ?? data.length);
  const totalPages = Number(res.headers.get("X-WP-TotalPages") ?? 1);

  return {
    posts: data.map(mapWpPost),
    totalPosts,
    totalPages,
    page,
  };
}

export async function fetchPost(slug: string, lang?: BlogLang): Promise<BlogPost | null> {
  const langParam = lang ? `?lang=${lang}` : "";
  const res = await fetch(`/api/blog/posts/${encodeURIComponent(slug)}${langParam}`);
  if (!res.ok) {
    if (res.status === 404) return null;
    throw new Error(`Failed to fetch post: ${res.status}`);
  }
  // /posts?slug=X returns an array (WP doesn't have a /posts/by-slug endpoint),
  // so [] here means the slug doesn't exist.
  const data = (await res.json()) as WpPost[];
  if (!Array.isArray(data) || data.length === 0) return null;
  const wpRaw = data[0];
  const mapped = mapWpPost(wpRaw);
  // Resolve translationSlug in a second fetch (only if Polylang points to a
  // counterpart). Fails silently — a missing pair is fine, a wrong pair
  // would send Google to a 404.
  const own: BlogLang = mapped.lang;
  mapped.translationSlug = await resolveTranslationSlug(wpRaw, own);
  return mapped;
}

export async function fetchRelatedPosts(post: BlogPost, limit = 3): Promise<BlogPost[]> {
  const firstCategory = post.categories[0]?.slug;
  if (!firstCategory) return [];

  const params = new URLSearchParams();
  params.set("category", firstCategory);
  params.set("per_page", String(limit + 1)); // +1 so we can drop the current post

  const res = await fetch(`/api/blog/posts?${params.toString()}`);
  if (!res.ok) return [];
  const data = (await res.json()) as WpPost[];
  return data
    .map(mapWpPost)
    .filter((p) => p.id !== post.id)
    .slice(0, limit);
}

export async function fetchCategories(): Promise<BlogCategory[]> {
  const res = await fetch("/api/blog/categories");
  if (!res.ok) return [];
  const data = (await res.json()) as Array<{ name: string; slug: string }>;
  return data.map((c) => ({ name: c.name, slug: c.slug }));
}

// Strip basic HTML tags — used for plain-text excerpts in cards and the
// meta description fallback. WP's excerpt field is HTML by default.
export function stripHtml(html: string): string {
  return html.replace(/<[^>]*>/g, "").replace(/\s+/g, " ").trim();
}

export function formatPostDate(iso: string): string {
  const d = new Date(iso);
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
}
